// 0x4d6340 createAndRegisterLogic. thiscall, 3 stack argument(s), returns u32.
uint32_t function_4d6340(Run &run, uint32_t receiver, const uint32_t *arguments) {
    uint32_t logic = run.call(0x4f63ec, 0, {0x174});
    if (logic != 0) {
        // Registrar +0x1c and +0x0c supply logic owner and context after allocation.
        uint32_t owner = run.get(receiver + 0x1c);
        uint32_t context = run.get(receiver + 0x0c);
        // Logic: vtable, owner, flags, context, callback, and three zero fields.
        run.put(logic + 0x04, owner);
        run.put(logic + 0x08, 0);
        run.put(logic + 0x0c, context);
        run.put(logic + 0x00, 0x513740);
        run.put(logic + 0x10, 0);
        run.put(logic + 0x14, 0);
        run.put(logic + 0x18, 0);
        run.put(logic + 0x1c, 0);
    }
    // The original also dereferences null here after allocation failure.
    // Vtable +0x24 initializes with callback and flags; +0x04 deletes on failure.
    uint32_t initialized = run.vcall(logic, 0x24, {arguments[0], arguments[2]});
    if (initialized == 0) {
        if (logic != 0) {
            run.vcall(logic, 0x04, {1});
        }
        return 0;
    }
    // Registrar +0x10 is the embedded name-to-logic map.
    uint32_t slot = run.call(0x4f62a8, receiver + 0x10, {arguments[1]});
    run.put(slot, logic);
    return logic;
}



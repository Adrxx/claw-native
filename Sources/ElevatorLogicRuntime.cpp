extern "C" uint32_t claw_elevator_entry(uint32_t f, uint32_t receiver, const uint32_t *args, uint32_t n,
                                        ClawElevatorContext *c, ClawElevatorDependency dependency, void *user,
                                        uint32_t *result) {
    (void)receiver;
    if (!c || !c->globals)
        return 0;
    uint32_t count = 1;
    switch (f) {
    case 0x49e060:
        count = 2;
        break;
    case 0x49e1c0:
        count = 3;
        break;
    case 0x49e2a0:
    case 0x49cdd0:
    case 0x49daf0:
    case 0x49db10:
    case 0x49db30:
    case 0x49db50:
    case 0x49db70:
        break;
    default:
        return 0;
    }
    if (n != count || !args) {
        c->fault = 3;
        return 0;
    }
    if (c->fault)
        return 0;
    Run r{c, dependency, user};
    uint32_t value = 1;
    switch (f) {
    case 0x49e060:
        phaseInit(r, args[0], args[1]);
        value = 0;
        break;
    case 0x49e1c0:
        absoluteMove(r, args[0], args[1], args[2]);
        value = 0;
        break;
    case 0x49e2a0:
        elevator(r, args[0]);
        break;
    default:
        if (f != 0x49cdd0)
            c->globals->wrapperMode = f == 0x49daf0   ? 20
                                      : f == 0x49db10 ? 21
                                      : f == 0x49db30 ? 22
                                      : f == 0x49db50 ? 23
                                                      : 24;
        gated(r, args[0]);
        break;
    }
    if (result)
        *result = value;
    return 1;
}


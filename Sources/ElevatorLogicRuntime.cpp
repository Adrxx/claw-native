struct Run {
    ClawElevatorContext *c;
    ClawElevatorDependency dependency;
    void *user;
};
int32_t signedWord(uint32_t v) {
    int32_t result;
    std::memcpy(&result, &v, 4);
    return result;
}
bool bad(Run &r) {
    return r.c->fault != 0;
}
uint32_t read(Run &r, uint32_t t) {
    if (bad(r))
        return 0;
    auto *p = r.c->scene.lookup ? r.c->scene.lookup(r.c->scene.context, t, 1) : nullptr;
    if (!p) {
        r.c->fault = 1;
        return 0;
    }
    return *p;
}
void write(Run &r, uint32_t t, uint32_t v) {
    if (bad(r))
        return;
    auto *p = r.c->scene.lookup ? r.c->scene.lookup(r.c->scene.context, t, 1) : nullptr;
    if (!p) {
        r.c->fault = 1;
        return;
    }
    *p = v;
}
uint32_t divide(Run &r, uint32_t a, uint32_t b) {
    if (bad(r))
        return 0;
    const int32_t x = signedWord(a), y = signedWord(b);
    if (!y || (x == std::numeric_limits<int32_t>::min() && y == -1)) {
        r.c->fault = 2;
        return 0;
    }
    return uint32_t(x / y);
}
uint32_t resolve(Run &r, uint32_t actor, uint32_t token, const char *name) {
    const uint32_t scene = read(r, actor + 0xc), registry = read(r, scene + 0x10) + 16;
    if (bad(r))
        return 0;
    if (!r.dependency) {
        r.c->fault = 1;
        return 0;
    }
    ClawElevatorCall e{0x4f6286, registry, 1, {token, 0, 0}, name};
    return r.dependency(r.c, &e, r.user);
}
void rect(Run &r, uint32_t actor, uint32_t offset) {
    const uint32_t source = r.c->globals->defaultsToken + offset;
    for (uint32_t i = 0; i < 16; i += 4) {
        const uint32_t v = read(r, source + i);
        write(r, actor + 0x128 + i, v);
    }
}
void imageRect(Run &r, uint32_t actor) {
    const uint32_t flags = read(r, actor + 8), image = read(r, actor + 0x174);
    write(r, actor + 0xd0, 0x80);
    write(r, actor + 8, flags | 1);
    if (!image || bad(r))
        return;
    uint32_t right = read(r, image + 0x20), left = read(r, image + 0x18);
    write(r, actor + 0x118, right - left);
    uint32_t bottom = read(r, image + 0x24), top = read(r, image + 0x1c);
    write(r, actor + 0x11c, bottom - top);
    left = read(r, image + 0x18);
    right = read(r, image + 0x20);
    write(r, actor + 0x120, left + right - 1);
    bottom = read(r, image + 0x24);
    top = read(r, image + 0x1c);
    write(r, actor + 0x124, top + bottom - 1);
}
bool level10(Run &r) {
    const uint32_t data = read(r, r.c->globals->managerToken + 0x2c);
    return read(r, data + 0x14) == 10 && !bad(r);
}
uint32_t serial(Run &r) {
    const uint32_t primary = read(r, r.c->globals->playerToken + 0x6c), privateToken = read(r, primary + 0x14);
    return read(r, privateToken + 0x80);
}
bool standing(Run &r, uint32_t actor) {
    const uint32_t player = r.c->globals->playerToken;
    if (!(read(r, player + 8) & 0x10) || bad(r))
        return false;
    return read(r, player + 0x80) == actor && !bad(r);
}
void reset(Run &r, uint32_t actor, uint32_t primary) {
    const uint32_t x = read(r, actor + 0xe8), y = read(r, actor + 0xec);
    write(r, actor + 0x4c, x);
    write(r, actor + 0x50, y);
    const uint32_t value = serial(r);
    write(r, primary + 0x1c, 0);
    write(r, primary + 0x64, value);
}
void phaseInit(Run &r, uint32_t actor, uint32_t p) {
    uint32_t distance = read(r, p + 0xc8);
    if (signedWord(distance) > 0) {
        const uint32_t half = distance / 2, x = read(r, actor + 0x4c);
        write(r, p + 0x2c, x - half);
        write(r, p + 0x30, half + read(r, actor + 0x4c));
    }
    distance = read(r, p + 0xcc);
    if (signedWord(distance) > 0) {
        const uint32_t half = distance / 2, y = read(r, actor + 0x50);
        write(r, p + 0x34, y - half);
        write(r, p + 0x38, half + read(r, actor + 0x50));
    }
    const uint32_t right = read(r, p + 0x30), left = read(r, p + 0x2c), top = read(r, p + 0x34),
                   bottom = read(r, p + 0x38);
    const uint32_t width = right - left + 1, height = bottom - top + 1;
    write(r, p + 0x3c, width);
    write(r, p + 0x40, height);
    if (signedWord(width) < 2)
        write(r, p + 0x3c, 0);
    if (signedWord(height) < 2)
        write(r, p + 0x40, 0);
    write(r, p + 0x4c, read(r, p + 0x3c) * 2);
    write(r, p + 0x50, read(r, p + 0x40) * 2);
    if (!read(r, actor + 0x148))
        write(r, actor + 0x148, 125);
    if (!read(r, actor + 0x14c))
        write(r, actor + 0x14c, 125);
    write(r, actor + 0x158, 0);
    write(r, actor + 0x15c, 0);
    uint32_t dx = read(r, actor + 0x4c) - read(r, p + 0x2c), dy = read(r, actor + 0x50) - read(r, p + 0x34);
    write(r, p + 0x44, dx);
    write(r, p + 0x48, dy);
    if (signedWord(dx) < 0)
        write(r, p + 0x44, 0);
    const uint32_t w = read(r, p + 0x3c);
    if (signedWord(read(r, p + 0x44)) > signedWord(w))
        write(r, p + 0x44, w);
    if (signedWord(read(r, p + 0x48)) < 0)
        write(r, p + 0x48, 0);
    const uint32_t h = read(r, p + 0x40);
    if (signedWord(read(r, p + 0x48)) > signedWord(h))
        write(r, p + 0x48, h);
    const uint32_t direction = read(r, actor + 0x110);
    if (direction == 7 || direction == 4 || direction == 1)
        write(r, p + 0x44, read(r, p + 0x44) + w);
    if (direction == 7 || direction == 8 || direction == 9)
        write(r, p + 0x48, read(r, p + 0x48) + h);
    uint32_t value = divide(r, read(r, p + 0x44) * 1000, read(r, actor + 0x148));
    write(r, p + 0x44, value);
    value = divide(r, read(r, p + 0x48) * 1000, read(r, actor + 0x14c));
    write(r, p + 0x48, value);
}
void absoluteMove(Run &r, uint32_t actor, uint32_t p, uint32_t tick) {
    for (uint32_t axis = 0; axis < 2; ++axis) {
        const uint32_t speed = read(r, actor + 0x148 + axis * 4);
        if (bad(r))
            return;
        if (signedWord(speed) <= 0)
            continue;
        const uint32_t period = read(r, p + 0x4c + axis * 4);
        if (bad(r))
            return;
        if (signedWord(period) <= 0)
            continue;
        const uint32_t offset = read(r, p + 0x44 + axis * 4), old = read(r, actor + 0x4c + axis * 4);
        const uint32_t remainder = ((offset + tick) * speed / 1000) % period;
        const uint32_t extent = read(r, p + 0x3c + axis * 4);
        uint32_t next;
        if (signedWord(remainder) > signedWord(extent))
            next = read(r, p + 0x30 + axis * 8) - remainder + extent;
        else
            next = read(r, p + 0x2c + axis * 8) + remainder;
        write(r, actor + 0x4c + axis * 4, next);
        write(r, actor + 0x158 + axis * 4, next - old);
    }
}
void elevator(Run &r, uint32_t actor) {
    const uint32_t p = read(r, actor + 0x6c), mode = read(r, p + 0x1c);
    if (bad(r))
        return;
    if (mode == 1) {
        absoluteMove(r, actor, p, r.c->globals->tick);
        return;
    }
    if (mode)
        return;
    phaseInit(r, actor, p);
    if (bad(r))
        return;
    imageRect(r, actor);
    rect(r, actor, 0x68);
    if (bad(r))
        return;
    if (level10(r)) {
        const uint32_t original = read(r, actor + 0x170), resolved = resolve(r, actor, 0x528a4c, "LEVEL_TRAPELEVATOR");
        if (!bad(r) && original == resolved)
            rect(r, actor, 0x98);
    }
    if (bad(r))
        return;
    if (read(r, p + 0x10) == 0x49e810)
        rect(r, actor, 0x88);
    const uint32_t original = read(r, actor + 0x170), resolved = resolve(r, actor, 0x52dd68, "LEVEL_STEPPINGSTONE");
    if (!bad(r) && original == resolved)
        rect(r, actor, 0x88);
    if (bad(r))
        return;
    write(r, actor + 0x134, read(r, actor + 0x134) + 32);
    if (!read(r, actor + 0x64)) {
        write(r, actor + 0x64, 2000);
        write(r, actor + 8, read(r, actor + 8) | 0x20000);
    }
    write(r, p + 0x1c, 1);
}
void gatedInit(Run &r, uint32_t actor, uint32_t p) {
    imageRect(r, actor);
    rect(r, actor, 0x68);
    if (bad(r))
        return;
    if (level10(r)) {
        const uint32_t original = read(r, actor + 0x170), resolved = resolve(r, actor, 0x528a4c, "LEVEL_TRAPELEVATOR");
        if (!bad(r) && original == resolved)
            rect(r, actor, 0x98);
    }
    if (bad(r))
        return;
    const uint32_t callback = read(r, p + 0x10);
    uint32_t mask = 0;
    bool alternate = false;
    switch (callback) {
    case 0x49daf0:
        mask = 2;
        break;
    case 0x49e810:
        alternate = true;
        break;
    case 0x49eb30:
        mask = 2;
        alternate = true;
        break;
    case 0x49db30:
        mask = 0x102;
        break;
    case 0x49ee20:
        mask = 0x102;
        alternate = true;
        break;
    case 0x49db50:
        mask = 0x1102;
        break;
    case 0x49db10:
        mask = 0x1002;
        break;
    case 0x49db70:
        mask = 1;
        break;
    default:
        break;
    }
    if (mask)
        write(r, actor + 0x164, read(r, actor + 0x164) | mask);
    if (alternate) {
        rect(r, actor, 0x88);
        write(r, actor + 0x110, 2);
    }
    write(r, actor + 0x134, read(r, actor + 0x134) + 32);
    for (uint32_t axis = 0; axis < 2; ++axis)
        for (uint32_t endpoint = 0; endpoint < 2; ++endpoint) {
            const uint32_t at = p + 0x2c + axis * 8 + endpoint * 4;
            if (!read(r, at))
                write(r, at, read(r, actor + 0x4c + axis * 4));
        }
    const uint32_t direction = read(r, actor + 0x110);
    if (!read(r, actor + 0x148))
        write(r, actor + 0x148, 125);
    if (!read(r, actor + 0x14c))
        write(r, actor + 0x14c, 125);
    if (direction == 6 || direction == 4)
        write(r, actor + 0x14c, 0);
    if (direction == 8 || direction == 2)
        write(r, actor + 0x148, 0);
    write(r, p + 0x1c, direction == 6 || direction == 2 || direction == 3 ? 1001 : 1000);
    const uint32_t value = serial(r);
    write(r, p + 0x64, value);
}
void gated(Run &r, uint32_t actor) {
    const uint32_t p = read(r, actor + 0x6c);
    uint32_t mode = read(r, p + 0x1c);
    if (bad(r))
        return;
    if (!mode) {
        gatedInit(r, actor, p);
        return;
    }
    uint32_t flags = read(r, actor + 0x164);
    if (flags & 2) {
        write(r, actor + 0x158, 0);
        write(r, actor + 0x15c, 0);
        if (!standing(r, actor)) {
            const uint32_t previous = read(r, p + 0x64), now = serial(r);
            if (bad(r) || previous == now)
                return;
            reset(r, actor, p);
            return;
        }
        if (flags & 0x1000)
            write(r, actor + 0x164, flags & ~2u);
    } else if (flags & 1) {
        write(r, actor + 0x158, 0);
        write(r, actor + 0x15c, 0);
        if (standing(r, actor) || bad(r))
            return;
    }
    if (bad(r))
        return;
    flags = read(r, actor + 0x164);
    if (flags & 0x1000) {
        const uint32_t previous = read(r, p + 0x64), now = serial(r);
        if (bad(r))
            return;
        if (previous != now) {
            reset(r, actor, p);
            return;
        }
    }
    mode = read(r, p + 0x1c);
    if (mode == 5) {
        write(r, actor + 0x158, 0);
        write(r, actor + 0x15c, 0);
        return;
    }
    if (mode != 1000 && mode != 1001)
        return;
    const bool positive = mode == 1001;
    uint32_t deltas[2]{};
    for (uint32_t axis = 0; axis < 2; ++axis) {
        const uint32_t position = read(r, actor + 0x4c + axis * 4),
                       bound = read(r, p + 0x2c + axis * 8 + (positive ? 4 : 0));
        const bool moving =
            positive ? signedWord(position) < signedWord(bound) : signedWord(bound) < signedWord(position);
        uint32_t delta = 0;
        if (moving) {
            delta = read(r, actor + 0x148 + axis * 4) * r.c->globals->animationDelta / 1000;
            if (!positive)
                delta = 0u - delta;
        }
        write(r, actor + 0x158 + axis * 4, delta);
        if (positive) {
            if (signedWord(delta) > 16)
                delta = 16;
        } else if (signedWord(delta) < -16)
            delta = uint32_t(-16);
        write(r, actor + 0x158 + axis * 4, delta);
        deltas[axis] = delta;
    }
    const uint32_t x = read(r, actor + 0x4c) + deltas[0], y = read(r, actor + 0x50) + deltas[1];
    write(r, actor + 0x4c, x);
    write(r, actor + 0x50, y);
    if (bad(r))
        return;
    const uint32_t bx = read(r, p + 0x2c + (positive ? 4 : 0));
    if (positive ? signedWord(x) < signedWord(bx) : signedWord(bx) < signedWord(x))
        return;
    const uint32_t by = read(r, p + 0x34 + (positive ? 4 : 0));
    if (positive ? signedWord(y) < signedWord(by) : signedWord(by) < signedWord(y))
        return;
    write(r, p + 0x1c, positive ? 1000 : 1001);
    if (read(r, actor + 0x164) & 0x100)
        write(r, p + 0x1c, 5);
}

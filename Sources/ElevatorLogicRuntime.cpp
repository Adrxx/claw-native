extern "C" uint32_t claw_elevator_initialize_profile(uint32_t level, ClawElevatorLevelProfile *p,
                                                     ClawElevatorSetRect setRect, void *user) {
    if (!p || signedWord(level) <= 0)
        return 0;
    std::fill_n(p->words, 48, 0);
    p->selectedToken = 0x5378a0;
    p->words[0] = level;
    p->levelWord = level;
    if (level > 14)
        return 0;
    const auto &operations = profiles[level - 1];
    for (size_t i = 0; i < operations.count; ++i) {
        const auto &o = operations.data[i];
        if (o.kind == 0)
            storeProfile(p, o.offset, o.values[0], o.size);
        else if (o.kind == 1)
            p->scaleWords[o.offset] = o.values[0];
        else if (setRect)
            setRect(p, o.offset, o.values, user);
        else
            std::copy_n(o.values, 4, p->words + o.offset / 4);
    }
    return 1;
}

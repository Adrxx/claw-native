void storeProfile(ClawElevatorLevelProfile *p, uint32_t offset, uint32_t value, uint32_t size) {
    for (uint32_t i = 0; i < size; ++i) {
        const uint32_t at = offset + i, shift = (at & 3) * 8;
        auto &word = p->words[at / 4];
        word = (word & ~(255u << shift)) | (((value >> (i * 8)) & 255u) << shift);
    }
}

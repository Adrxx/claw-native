// Stack-argument count of each owned function, or -1.
int owned(uint32_t function) {
    switch (function) {
    case 0x46fd10:
        return 1;
    case 0x470110:
        return 1;
    case 0x4719e0:
        return 1;
    case 0x4736b0:
        return 1;
    default:
        return -1;
    }
}


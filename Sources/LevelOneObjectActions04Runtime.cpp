// 0x4719e0 as an owned callee: the caller pushes the world and the call
// pushes a return word, so the argument sits at `caller frame + pushed`.
void buildTablesFrom(Run &run, uint32_t world, int32_t slotOffset) {
    uint32_t slot = run.automatic(slotOffset);
    run.put(slot, world);
    buildTables(run, slot);
}

// Position of `key` in the kind keys, or -1 when absent (count read once).
int32_t findKind(Run &run, uint32_t count, uint32_t key) {
    int32_t index = 0;
    if (s32(count) > 0) {
        uint32_t address = 0x537ec8;
        do {
            if (run.get(address) == key)
                return index;
            ++index;
            address += 4;
        } while (index < s32(count));
    }
    return -1;
}

// 0x46fd10. Treasure and powerup object logic, keyed on the state word at
// [[obj+0x6c]+0x1c]: 0 initialises, 5 animates, 0x2328 starts the fly-to-HUD
// motion, 0x2329 runs it, 0x1d releases the glitter object.
uint32_t function_46fd10(Run &run, uint32_t receiver, const uint32_t *arguments) {
    (void)receiver;
    uint32_t obj = arguments[0];
    uint32_t logic = run.get(obj + 0x6c);
    uint32_t state = run.get(logic + 0x1c);
    if (state > 5) {
        if (state == 0x1d) {
            uint32_t glitter = run.get(obj + 0xc8);
            if (glitter != 0) {
                uint32_t flags = run.get(glitter + 0x8);
                flags |= 0x10000;
                run.put(glitter + 0x8, flags);
                run.put(obj + 0xc8, 0);
            }
            return 1;
        }
        if (state == 0x2328) {
            uint32_t flags = run.get(obj + 0x8);
            uint32_t glitter = run.get(obj + 0xc8);
            flags |= 0x21;
            run.put(obj + 0x8, flags);
            if (glitter != 0) {
                uint32_t glitterFlags = run.get(glitter + 0x8);
                glitterFlags |= 0x10000;
                run.put(glitter + 0x8, glitterFlags);
                run.put(obj + 0xc8, 0);
            }
            uint32_t scene = run.get(obj + 0xc);
            uint32_t map = run.get(scene + 0x24);
            uint32_t plane = run.get(map + 0x5c);
            uint32_t targetX = run.get(plane + 0x84);
            uint32_t targetY = run.get(plane + 0x88);
            run.put(logic + 0x130, 0x190);
            uint32_t x = run.get(obj + 0x4c);
            targetX -= 0x12c;
            targetY -= 0x118;
            x *= 1000;
            targetX *= 1000;
            x -= targetX;
            run.put(logic + 0x64, x / 400);
            uint32_t y = run.get(obj + 0x50);
            run.put(logic + 0x1c, 0x2329);
            y *= 1000;
            targetY *= 1000;
            y -= targetY;
            run.put(logic + 0x68, y / 400);
            run.call(0x4737c0, 0, {obj});
            return 1;
        }
        if (state == 0x2329) {
            uint32_t remaining = run.get(logic + 0x130);
            uint32_t tick = run.get(0x53720c);
            if (tick < remaining)
                run.put(logic + 0x130, remaining - tick);
            else
                run.put(logic + 0x130, 0);
            if (run.get(logic + 0x130) == 0) {
                uint32_t flags = run.get(obj + 0x8);
                flags |= 0x10000;
                run.put(obj + 0x8, flags);
            }
            uint32_t velocityX = run.get(logic + 0x64);
            if (velocityX != 0) {
                uint32_t delta = run.get(0x53720c);
                delta *= velocityX;
                uint32_t position = run.get(obj + 0x4c);
                position -= delta / 1000;
                run.put(obj + 0x4c, position);
            }
            uint32_t velocityY = run.get(logic + 0x68);
            if (velocityY != 0) {
                uint32_t delta = run.get(0x53720c);
                delta *= velocityY;
                uint32_t position = run.get(obj + 0x50);
                position -= delta / 1000;
                run.put(obj + 0x50, position);
            }
            uint32_t step = run.get(0x5430c4);
            run.call(0x4c82a0, obj + 0x188, {step});
            return 1;
        }
        return 1;
    }
    if (state == 5) {
        uint32_t step = run.get(0x5430c4);
        run.call(0x4c82a0, obj + 0x188, {step});
        uint32_t status = run.get(obj + 0x164);
        if ((status & 0x200) != 0)
            run.put(logic + 0x1c, 0x2328);
        return 1;
    }
    if (state != 0)
        return 1;
    uint32_t slot = run.automatic(4);
    run.put(logic + 0x168, 0);
    uint32_t life = run.get(obj + 0x64);
    run.put(obj + 0xc8, 0);
    if (life == 0) {
        uint32_t flags = run.get(obj + 0x8);
        run.put(obj + 0x64, 0x3e8);
        flags |= 0x20000;
        run.put(obj + 0x8, flags);
    }
    if (run.get(obj + 0x190) == 0) {
        uint32_t scene = run.get(obj + 0xc);
        uint32_t kind = run.get(obj + 0x170);
        run.put(slot, 0);
        uint32_t registry = run.get(scene + 0x10);
        registry += 0x10;
        run.call(0x4f6286, registry, {0x5279b8, slot});
        uint32_t coins = run.get(slot);
        uint32_t name = 0x52a198;
        if (kind == coins)
            name = 0x5240d8;
        run.call(0x4c79e0, obj, {name, 0});
    }
    uint32_t flags = run.get(obj + 0x8);
    uint32_t bounds = run.get(obj + 0x174);
    flags |= 0x80000;
    run.put(obj + 0x8, flags);
    run.put(obj + 0xd0, 0x40000);
    if (bounds != 0) {
        uint32_t right = run.get(bounds + 0x20);
        uint32_t left = run.get(bounds + 0x18);
        right -= left;
        run.put(obj + 0x138, right);
        uint32_t bottom = run.get(bounds + 0x24);
        bottom -= run.get(bounds + 0x1c);
        run.put(obj + 0x13c, bottom);
        right = run.get(bounds + 0x20);
        left = run.get(bounds + 0x18);
        right = right + left - 1;
        run.put(obj + 0x140, right);
        bottom = run.get(bounds + 0x24);
        uint32_t top = run.get(bounds + 0x1c);
        bottom = bottom + top - 1;
        run.put(obj + 0x144, bottom);
    }
    uint32_t hitLeft = run.get(obj + 0x138);
    uint32_t hitTop = run.get(obj + 0x13c);
    uint32_t hitRight = run.get(obj + 0x140);
    uint32_t hitBottom = run.get(obj + 0x144);
    hitLeft += 0xfffffffa;
    hitTop += 0xfffffff6;
    hitRight += 6;
    hitBottom += 2;
    run.put(obj + 0x138, hitLeft);
    run.put(obj + 0x13c, hitTop);
    run.put(obj + 0x140, hitRight);
    run.put(obj + 0x144, hitBottom);
    if (run.get(0x538418) == 0)
        buildTablesFrom(run, run.get(obj + 0xc), -0x14);
    uint32_t count = run.get(0x52a190);
    uint32_t kind = run.get(obj + 0x170);
    int32_t found = findKind(run, count, kind);
    if (found >= 0) {
        uint32_t index = uint32_t(found);
        run.put(obj + 0x4, index);
        if (index == 0)
            run.put(obj + 0x4, 0x21);
        uint32_t value = run.get(0x537fd0 + index * 4);
        uint32_t objLogic = run.get(obj + 0x6c);
        run.put(obj + 0xfc, value);
        uint32_t step = run.get(0x538310 + index * 4);
        run.put(objLogic + 0x168, step);
        uint32_t current = run.get(obj + 0xd0);
        if (current == 1) {
            uint32_t flagWord = run.get(0x5380d8 + index * 4);
            run.put(obj + 0xd0, flagWord);
        }
    } else {
        uint32_t objLogic = run.get(obj + 0x6c);
        run.put(obj + 0x4, 0);
        run.put(obj + 0xfc, 0x64);
        run.put(objLogic + 0x168, 0);
    }
    uint32_t handler = run.get(logic + 0x10);
    uint32_t glitter = 0;
    if (handler != 0x470100) {
        uint32_t environment = run.get(0x5371fc);
        if (run.get(environment + 0x124) != 0) {
            uint32_t life2 = run.get(obj + 0x64);
            uint32_t y = run.get(obj + 0x50);
            uint32_t x = run.get(obj + 0x4c);
            life2 += 1;
            uint32_t scene = run.get(obj + 0xc);
            uint32_t factory = run.get(scene + 0x8);
            glitter = run.call(0x4c8da0, factory, {1, x, y, life2, 0x522950, 0x40000});
        }
    }
    if (glitter != 0)
        run.put(obj + 0xc8, glitter);
    run.put(logic + 0x1c, 5);
    return 1;
}

// 0x470110. Glitter object logic: state 0 sets up the animation and picks a
// random phase, state 5 animates.
uint32_t function_470110(Run &run, uint32_t receiver, const uint32_t *arguments) {
    (void)receiver;
    uint32_t obj = arguments[0];
    uint32_t logic = run.get(obj + 0x6c);
    uint32_t state = run.get(logic + 0x1c);
    if (state != 0) {
        if (state != 5)
            return 1;
        uint32_t step = run.get(0x5430c4);
        run.call(0x4c82a0, obj + 0x188, {step});
        return 1;
    }
    run.put(logic + 0x168, 0);
    run.call(0x4c7970, obj, {0x52a1a8});
    uint32_t life = run.get(obj + 0x64);
    if (life == 0) {
        uint32_t flags = run.get(obj + 0x8);
        run.put(obj + 0x64, 0x3e9);
        flags |= 0x20000;
        run.put(obj + 0x8, flags);
    }
    uint32_t animation = run.get(obj + 0x190);
    if (animation == 0)
        run.call(0x4c79e0, obj, {0x5240d8, 0});
    run.put(logic + 0x1c, 5);
    uint32_t random = run.call(0x4a3050, 0, {});
    int32_t phase = s32(random) % 0xfb;
    run.put(logic + 0x20, uint32_t(phase));
    return 1;
}


"""Capture original PCX physical spans; file tails are declared fixture memory.

This does not bless a retail out-of-file read. Tight-file calls compare the
entire unchanged heap/event prefix at the first original forbidden read.
Run after the base PCX comparison; generated bytes stay ignored under work/.
"""
import ctypes as C
import hashlib
import json
import struct
import pcx_image_helpers as H
from unicorn import UC_HOOK_MEM_READ, UC_HOOK_MEM_WRITE
from unicorn.x86_const import UC_X86_REG_EIP

WORK = H.ROOT / 'work/root-pcx-spans'
WORK.mkdir(exist_ok=True)
profiles = []
prefixes = 0
for index, path in enumerate(sorted((H.ROOT / 'work/original-disc-assets').rglob('*.PCX'))):
    raw = path.read_bytes()
    x, y, X, Y = struct.unpack_from('<4h', raw, 4)
    width, height, planes, padding = X-x+1, Y-y+1, raw[65], index % 4
    visible = (width * planes + padding) * height
    H.prepare(width, height, planes, padding=padding)
    H.write(H.DATA, raw)
    initial = H.read(H.DATA, H.PIXELS-H.DATA)
    touched = {'readEnd': 0, 'writeEnd': visible}

    def observe_read(u, access, address, size, value, user):
        touched['readEnd'] = max(touched['readEnd'], address-H.DATA+size)

    def observe_write(u, access, address, size, value, user):
        touched['writeEnd'] = max(touched['writeEnd'], address-H.PIXELS+size)

    handles = [
        H.m.u.hook_add(UC_HOOK_MEM_READ, observe_read, begin=H.DATA, end=H.PIXELS-1),
        H.m.u.hook_add(UC_HOOK_MEM_WRITE, observe_write, begin=H.PIXELS, end=H.TEMP-1),
    ]
    try:
        assert H.compare(0x4bebc0, H.SURFACE, [H.MANAGER, H.DATA, len(raw)], ('rootPhysicalSpan', str(path.relative_to(H.ROOT))), False) == 1
    finally:
        for handle in handles:
            H.m.u.hook_del(handle)
    input_bytes = max(len(raw), touched['readEnd'])
    backing = initial[:input_bytes]
    result = H.read(H.PIXELS, touched['writeEnd'])
    (WORK/f'{index}.input').write_bytes(backing)
    (WORK/f'{index}.surface').write_bytes(result)
    (WORK/f'{index}.before.surface').write_bytes(H.baseSeed[H.PIXELS-H.BASE:H.PIXELS-H.BASE+touched['writeEnd']])
    profile = dict(index=index, path=str(path.relative_to(H.ROOT)), width=width,
                   height=height, planes=planes, padding=padding, fileBytes=len(raw),
                   inputBytes=input_bytes, readEnd=touched['readEnd'], visibleBytes=visible,
                   surfaceBytes=touched['writeEnd'], fileSHA256=hashlib.sha256(raw).hexdigest(),
                   inputSHA256=hashlib.sha256(backing).hexdigest(),
                   surfaceSHA256=hashlib.sha256(result).hexdigest())
    profiles.append(profile)
    if touched['readEnd'] > len(raw):
        # Exact-file input: stop original immediately before the missing read.
        H.prepare(width, height, planes, padding=padding)
        H.write(H.DATA, raw)
        H.sync()
        H.events[0].clear(); H.events[1].clear(); H.errors.clear()
        hit = []

        def stop_at_file_end(u, access, address, size, value, user):
            if address+size > H.DATA+len(raw):
                hit.append((u.reg_read(UC_X86_REG_EIP), address, size))
                u.emu_stop()

        handle = H.m.u.hook_add(UC_HOOK_MEM_READ, stop_at_file_end, begin=H.DATA, end=H.PIXELS-1)
        try:
            try:
                H.m.call(0x4bebc0, H.SURFACE, struct.pack('<3I', H.MANAGER, H.DATA, len(raw)), max_instructions=500000000)
            except AssertionError:
                assert hit
        finally:
            H.m.u.hook_del(handle)

        @H.Bytes
        def tight_bytes(user, token, count):
            if H.DATA <= token < H.PIXELS and token+count > H.DATA+len(raw):
                return 0
            return H.byteLookup(user, token, count)

        H.context.bytes = tight_bytes
        H.context.fault = 0
        args = (H.U*3)(H.MANAGER, H.DATA, len(raw)); out = H.U()
        try:
            assert not H.lib.claw_pcx_image_entry(0x4bebc0, H.SURFACE, args, 3, C.byref(H.context), H.dependency, None, C.byref(out))
            assert H.context.fault == 1 and len(hit) == 1
            assert H.snapshot(True) == H.snapshot(False) and H.events[0] == H.events[1]
            profile['tightFilePrefix'] = dict(instruction=hex(hit[0][0]), offset=hit[0][1]-H.DATA, readBytes=hit[0][2])
            (WORK/f'{index}.prefix.surface').write_bytes(H.read(H.PIXELS, touched['writeEnd']))
            prefixes += 1
        finally:
            H.context.bytes = H.byteLookup
    if index % 40 == 0:
        print('Captured original PCX spans', index+1, 'of469', flush=True)

report = dict(originalSHA256=hashlib.sha256((H.ROOT/'Original/claw10/CLAW.EXE').read_bytes()).hexdigest(),
              wholeOriginalCalls=H.calls, orderedSnapshots=H.eventCount, retailFiles=len(profiles),
              tightFilePrefixes=prefixes, maximumInputTail=max(p['inputBytes']-p['fileBytes'] for p in profiles),
              maximumSurfaceTail=max(p['surfaceBytes']-p['visibleBytes'] for p in profiles),
              profile='Seed721 fixture memory only; out-of-file reads are not retail boot acceptance')
(WORK/'profiles.json').write_text(json.dumps(profiles, indent=2)+'\n')
(WORK/'report.json').write_text(json.dumps(report, indent=2)+'\n')
(WORK/'replay-manifest.txt').write_text('\n'.join(' '.join(str(p[k]) for k in ('index','width','height','planes','padding','fileBytes','inputBytes','surfaceBytes')) for p in profiles)+'\n')
print('PASS root PCX physical-span/prefix capture', json.dumps(report, sort_keys=True), flush=True)

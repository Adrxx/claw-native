"""In-game Options > Display through real key events, compared with the original trace.

Owner crash 2026-10-23 (app-owner-crash-ingame-display-options): Level 1, Escape menu > Options >
Display stopped the app. This check launches its own muted Release (or CLAW_CONFIG) instance on the
real clock with a scratch --save-dir, walks the menu to Level 1, then posts real window-server key
events to that process only (scripts/post-window-input.swift): Escape, Options, Display, Front Layer
off and on, Game Play Area ten steps down and ten up, Movies twice, Back, and Escape, which resumes play.

Expected behaviour comes from work/display-options/orig.json, generated by orig_trace.py from
the hash-checked original binary (0x451230 handles commands 0x5b05..0x5b08):
the state is the in-game menu 0x50c044 until the final Escape resumes single-player 0x50c264; Front Layer
toggles application +0x128 and repaints through 0x450380 -> 0x46dd90, so exactly its two Return frames
present twice; Movies toggles application +0x120 only; the Game Play Area at its smallest changes the
application's scalar words and returning it to full restores them. At front-on, area-max and movies-2 every
scalar application word equals the one at the page's first frame. Screenshots go to
work/display-options/check/. It closes only the instance it started. A missing, stopped or incomplete
original trace fails before launching the app.

Usage: work/test-env/bin/python scripts/check-ingame-display-options.py [--config Release] [--real-time]
Runs on the fast clock through the app's input gate (scripts/real_input.py); --real-time (or REAL_TIME=1)
keeps the display timer and wall-clock waits for pacing checks.
Prints one JSON line last.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from real_input import Session, build_helper, real_time_requested  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "work" / "display-options"
OUT = WORK / "check"
HELPER = WORK / "post-window-input"
STEPS = (["esc", "down", "down", "ret", "down", "ret", "#disp", "ret", "#front-off", "ret", "#front-on", "down"]
         + ["left"] * 10 + ["#area-min"] + ["right"] * 10 + ["#area-max"]
         + ["down", "ret", "#movies-1", "ret", "#movies-2", "down", "ret", "#back", "esc", "#resumed"])
SETTING_OFFSETS = (0x68, 0x120, 0x128)
ORIGINAL_SHA256 = "350b8d51e1cd52037cd31a7722197a815e4206e7d3052ec632465f1354726263"
MAC = {"esc": 53, "down": 125, "up": 126, "ret": 36, "left": 123, "right": 124}
MENU, LEVEL = "50c044", "50c264"
MENU_KEYS = [{"ms": ms + d, "key": 13, "down": 1 - d // 80} for ms in (3000, 5000, 7000) for d in (0, 80)]


def claw_pids():
    found = subprocess.run(["pgrep", "-x", "Claw"], capture_output=True, text=True).stdout.split()
    return {int(p) for p in found}


def read(name):
    try:
        return json.loads((OUT / name).read_text())
    except (OSError, ValueError):
        return {}


def wait(predicate, seconds):
    end = time.monotonic() + seconds
    while time.monotonic() < end:
        if predicate():
            return True
        time.sleep(0.05)
    return False


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default=os.environ.get("CLAW_CONFIG", "Release"))
    parser.add_argument("--real-time", action="store_true", help="the display timer and wall-clock waits (pacing check)")
    parser.add_argument("--original", type=Path, default=WORK / "orig.json")
    args = parser.parse_args()
    fast = not real_time_requested(args.real_time)
    derived_data = Path(os.environ.get("CLAW_DERIVED_DATA", ROOT / "work" / "MacCatalyst"))
    app = derived_data.resolve() / "Build" / "Products" / f"{args.config}-maccatalyst" / "Claw.app"
    result = {"check": "ingame-display-options", "status": "fail", "config": args.config, "fast": fast, "errors": []}
    errors = result["errors"]
    steps = [{"key": k} if not k.startswith("#") else {"mark": k[1:]} for k in STEPS]
    try:
        original = json.loads(args.original.read_text())
        reference = original["display_steps"]
        if original.get("stop") is not None or original.get("status") != "pass":
            raise ValueError("original trace did not finish")
        if original.get("original_sha256") != ORIGINAL_SHA256:
            raise ValueError("original binary hash differs")
        if os.environ.get('PAPER') == '1' and (original.get('startup_profile') != dict(paper=True, query_ms=1)
                or not original.get('startup_queries', {}).get('count')
                or original['startup_queries']['increments'] != {'1': original['startup_queries']['count']}
                or (original.get('resumed_checkpoint') and
                    (original.get('parent_checkpoint') or {}).get('startup_profile') != dict(paper=True, query_ms=1))):
            raise ValueError('PAPER=1 requires original paper startup and verified parent provenance')
        route = [e.get("key", "#" + e.get("mark", "")) for e in reference]
        if route != STEPS:
            raise ValueError("original trace route differs or is incomplete")
        for entry in reference:
            int(entry["vtable"], 16)
            if "mark" in entry:
                for offset in SETTING_OFFSETS:
                    if not isinstance(entry["settings"][hex(offset)], int):
                        raise ValueError("original trace setting is not an integer")
            elif not entry["presentations"] or any(n not in (1, 2) for n in entry["presentations"]):
                raise ValueError("original trace has missing or invalid frame presentations")
    except (OSError, ValueError, KeyError, TypeError) as error:
        errors.append(f"original reference: {error}")
        print(json.dumps(result))
        return 1
    build_helper(HELPER)
    subprocess.run(["rm", "-rf", str(OUT)], check=True)
    OUT.mkdir(parents=True)
    (OUT / "menu-keys.json").write_text(json.dumps(MENU_KEYS))
    session = Session(OUT, fast=fast, helper=HELPER)
    pid = None
    log = []
    marks = {}
    try:
        pid = session.launch(app, {"CLAW_REAL_SPEED_KEYS": OUT / "menu-keys.json"},
                             ["--new-game-clock", "--stationary-cursor", "--save-dir", str(OUT / "saves"), "--menu-live-check", str(OUT), "-ClawCheckDirectory", str(OUT)])
        # The original's standing period starts at Level 1 initialization.
        # A readiness wait of 1500 ms followed by another second advanced the
        # animated backdrop before Escape, so marker pixels could never match.
        # Keep the retained physical plan's 1000 ms stand, without an extra
        # gameplay readiness delay; single-frame polling avoids overshooting it.
        standing_ms = original.get("input_schedule", {}).get("standing_ms", 1000)
        if not session.wait(lambda: (read("live.json").get("weapons") or {}).get("weapon") is not None
                            and read("live.json").get("game_ms", 0) >= standing_ms, 90, step=1):
            raise RuntimeError("Level 1 did not start")
        for index, step in enumerate(steps):
            expected = reference[index]
            if "mark" in step:
                name = step["mark"]
                record = session.mark(name)
                if record is None:
                    errors.append(f"{name}: no presented frame record")
                    continue
                marks[name] = record.get("application_words") or []
                if expected.get('screen'):
                    for field in ('pixels_sha256', 'palette_sha256'):
                        if record.get(field) != expected['screen'][field]:
                            errors.append(f'{name}: {field} differs from original')
                state = read("live-state.json")
                want_state = expected["vtable"].removeprefix("0x")
                if state.get("status") != "running" or state.get("state_vtable") != want_state:
                    errors.append(f"{name}: state {state.get('state_vtable')} != original {want_state}")
                for offset in SETTING_OFFSETS:
                    actual = marks[name][offset // 4] if len(marks[name]) > offset // 4 else None
                    want = expected["settings"][hex(offset)]
                    if actual != want:
                        errors.append(f"{name}: application +{hex(offset)} {actual} != original {want}")
                continue
            if fast and index == len(steps) - 2:
                # DisplayTrace retains the menu's 1 ms query increment through
                # resume. Keep that service profile instead of switching to the
                # usual gameplay clock; no frame or physical key is added.
                session.query_step(1)
            first = read("live.json").get("frame", 0)
            for direction in ("down", "up"):
                session.post("press", MAC[step["key"]], direction)
                session.sleep(0.12)
            session.sleep(0.5)
            state = read("live-state.json")
            if state.get("status") != "running":
                errors.append(f"{step['key']}: app {state.get('status')} {state.get('error')}")
                break
            vtable = state.get("state_vtable")
            want = expected["vtable"].removeprefix("0x")
            if vtable != want:
                errors.append(f"{step['key']} (step {index}): state {vtable} != {want}")
            log.append({"key": step["key"], "state": vtable, "frames": [first, read("live.json").get("frame", 0)],
                        "double": 2 in expected["presentations"],
                        "expected_presentations": expected["presentations"],
                        "expected_extra_presentations": [n for n in expected["presentations"] if n > 1]})
    except Exception as error:  # noqa: BLE001 - reported as the check's failure
        errors.append(str(error))
    finally:
        try:
            if pid:
                session.sleep(1.0)
        except Exception as error:  # retain route failure even if the final wait fails
            errors.append(f"final wait: {error}")
        finally:
            session.close()
    # Frames that present twice: only the Front Layer Returns (0x5b05 -> 0x450380).
    speed = read("real-speed.json")
    # The log interleaves input receipt rows with completed-frame rows. An
    # input receipt has the next frame number but is not a rendered frame.
    frame_records = [f for f in speed.get("frames", []) if "presentations" in f]
    doubles = [f["frame"] for f in frame_records if f["presentations"] > 1]
    if len(log) != sum("key" in e for e in reference):
        errors.append("key route did not finish")
    for entry in log:
        if "key" in entry:
            lo, hi = entry["frames"]
            if not any(lo < f["frame"] <= hi for f in frame_records):
                errors.append(f"{entry['key']} frames {lo}-{hi}: no presentation evidence")
            if fast:
                actual_frames = [f["presentations"] for f in frame_records
                                 if lo < f["frame"] <= hi]
                if actual_frames != entry["expected_presentations"]:
                    errors.append(f"{entry['key']} frames {lo}-{hi}: presentation sequence differs from original "
                                  f"({len(actual_frames)} frames, expected {len(entry['expected_presentations'])})")
            # Real time: live.json can trail the presented frame by up to two frames; the gate's is exact.
            actual = [f["presentations"] for f in frame_records
                      if lo < f["frame"] <= hi + (0 if fast else 2) and f["presentations"] > 1]
            if actual != entry["expected_extra_presentations"]:
                errors.append(f"{entry['key']} frames {lo}-{hi}: extra presentations {actual}, "
                              f"original {entry['expected_extra_presentations']}")
    # Application +0x18, +0x20 and +0x24 run on every frame and message (the original's +0x20 moves on the
    # in-game Escape alone), so they are not display settings.
    def scalars(words):
        return {4 * i: w for i, w in enumerate(words) if 0 <= w < 0x10000000 and 4 * i not in (0x18, 0x20, 0x24)}
    base = scalars(marks.get("disp", []))
    if not base:
        errors.append("no application words at the Display page")
    else:
        def changed(name):
            now = scalars(marks.get(name, []))
            return sorted(hex(o) for o in set(base) | set(now) if base.get(o) != now.get(o))
        expect = {"front-off": ["0x128"], "front-on": [], "area-max": [], "movies-1": ["0x120"], "movies-2": []}
        for name, offsets in expect.items():
            if changed(name) != offsets:
                errors.append(f"{name}: application words changed {changed(name)}, expected {offsets}")
        if changed("area-min") != ["0x68"]:
            errors.append(f"area-min: the smallest Game Play Area changed {changed('area-min')}, expected application +0x68")
        result["area_min_changed"] = changed("area-min")
    final = read("live-state.json")
    if final.get("state_vtable") != LEVEL:
        errors.append(f"after resume: state {final.get('state_vtable')}")
    expected_commands = [hex(e["wparam"]) for e in original.get("window_messages", [])
                         if e.get("service") == "PostMessageA" and e.get("message") == 0x111]
    actual_commands = read("live.json").get("posted_commands", [])
    if expected_commands and actual_commands != expected_commands:
        errors.append(f"posted window commands {actual_commands}, original {expected_commands}")
    result["window_commands"] = {"app": actual_commands, "original": expected_commands}
    result.update(retries=session.retries, steps=len(log), doubles=doubles, marks=list(marks),
                  original=str(args.original), original_steps=len(reference),
                  original_sha256=hashlib.sha256(args.original.read_bytes()).hexdigest(),
                  startup_profile=original.get('startup_profile'),
                  compared_screens=sum('screen' in e for e in reference),
                  compared_frames=sum(len(e["expected_presentations"]) for e in log) if fast else None)
    # Evidence compared between the fast and real-time runs (scripts/compare-real-input.py): no frame numbers.
    (OUT / "evidence.json").write_text(json.dumps({"states": [[e["key"], e["state"], e["double"]] for e in log],
        "marks": {k: {hex(o): w for o, w in scalars(v).items()} for k, v in sorted(marks.items())}, "final_state": final.get("state_vtable"),
        "double_count": len(doubles), "area_min_changed": result.get("area_min_changed")}, indent=1, sort_keys=True))
    if not errors:
        result["status"] = "pass"
    (WORK / 'result.json').write_text(json.dumps(result, indent=1, sort_keys=True))
    print(json.dumps(result))
    return 0 if result["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())

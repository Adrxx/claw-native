"""In-game Escape menu loops in Level 1 through real key events: Return to Game, End Life No and Yes, End Game
No and Yes, losing the last life (game over) and a fresh New Game afterwards, checked step by step against the
original route as well as the admitted handlers.

This check launches its own muted Release (or CLAW_CONFIG) instance with a scratch
--save-dir, walks the menu to Level 1 and posts real window-server key events to that process only
(scripts/post-window-input.swift), as scripts/check-ingame-audio-options.py does. At each mark the app records
the presented frame (indexed pixels and palette hashes), the current state's vtable, the player's counters
(lives private +0x7c, lives lost +0x80, health, game clock 0x537210, held keys) and every posted command.

Expected behaviour comes from the admitted original handlers:
  Escape in Level 1 posts 0x8080 and enters the in-game menu state (vtable 0x50c044, family in_game_menu);
    the game clock 0x537210 the level sees on resume is the one it had when the menu opened.
  Return to Game, command 0x4e21 (pause_menu_input 0x450cf0): posts 0x8036 and play resumes (vtable 0x50c264)
    with the same lives and no held key.
  End Life (0x4e22) opens its Yes/No page; No, 0x55f2 (pause_menu_commands 0x451410), returns to the main page
    without a posted command; Escape then resumes with lives unchanged.
  End Life Yes, 0x55f1: posts 0x8036 then 0x8063; the player dies (0x41c440): lives go down by one, lives lost
    up by one, and play resumes at the checkpoint (0x803a respawn).
  End Game (0x4e25) opens its Yes/No page; No, 0x5dc2 (0x451530), returns to the main page.
  When the last life is lost, 0x41c440 posts 0x8006 instead of 0x803a. With application +0x9c clear (the
    retail, non-Nani build) 0x8006 goes to the menu state 5 (vtable 0x50c1e4), not the Nani game over state 12
    (vtable 0x50bfec): the single-player game over is the return to the menu (player_death_commands).
  New Game from there starts Level 1 again with the starting lives.
  End Game Yes, 0x5dc1: posts 0x8036 then 0x8023 (application +0x9c clear) and the menu state 5 follows.
The required local original reference is work/pause-gameover/original.json, generated by the diagnostic
tracer beside it. Every mark compares the state, ordered commands, lives, lives lost, and both presented
screen hashes. Missing, incomplete, or mismatching original evidence fails the check.
It closes only the instance it started.

Usage: work/test-env/bin/python scripts/check-pause-gameover.py [--config Release] [--real-time]
Runs on the fast clock through the app's input gate (scripts/real_input.py); --real-time (or REAL_TIME=1)
keeps the display timer and wall-clock waits for pacing checks.
Prints one JSON line last.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from real_input import Session, build_helper, real_time_requested  # noqa: E402
from responsiveness import check_heartbeats

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "work" / "pause-gameover"
HELPER = ROOT / "work" / "audio-options" / "post-window-input"
MAC = {"esc": 53, "down": 125, "up": 126, "ret": 36, "left": 123, "right": 124}
PAUSE, LEVEL, MENU = "0x50c044", "0x50c264", "0x50c1e4"
MENU_KEYS = [{"ms": ms + d, "key": 13, "down": 1 - d // 80} for ms in (3000, 5000, 7000) for d in (0, 80)]
END_LIFE = ["esc", "down", "ret"]          # main page: Return, End Life, Options, Help, End Game
END_GAME = ["esc", "down", "down", "down", "down", "ret"]
MARKS = ("play", "pause", "pause-held", "resume", "endlife-page", "endlife-no", "endlife-no-resume",
         "endgame-page", "endgame-no", "endgame-no-resume", "endlife-yes-1", "endlife-yes-2",
         "gameover-menu", "newgame", "endgame-page-2", "endgame-yes")
ORIGINAL_SHA256 = "350b8d51e1cd52037cd31a7722197a815e4206e7d3052ec632465f1354726263"


def original_reference(path):
    reference = json.loads(path.read_text())
    if reference.get("status") != "pass" or reference.get("stop") is not None:
        raise ValueError("original pause route is incomplete")
    if reference.get("original_sha256") != ORIGINAL_SHA256:
        raise ValueError("original pause route has the wrong reference binary")
    marks = reference.get("marks", [])
    if [m.get("mark") for m in marks] != list(MARKS):
        raise ValueError("original pause route has missing, duplicated, or reordered marks")
    for mark in marks:
        for field in ("pixels_sha256", "palette_sha256"):
            value = mark.get("presentation", {}).get(field, "")
            if len(value) != 64 or any(c not in "0123456789abcdef" for c in value):
                raise ValueError(f"original {mark['mark']}: missing {field}")
        if not isinstance(mark.get("posted"), list) or not mark.get("state_vtable"):
            raise ValueError(f"original {mark['mark']}: missing state or command sequence")
        if mark["state_vtable"] != MENU:
            if any(not isinstance(mark.get("player", {}).get(f), int) for f in ("lives", "lives_lost")):
                raise ValueError(f"original {mark['mark']}: missing player counters")
    return {m["mark"]: m for m in marks}


def compare_original(name, mark, posted, expected):
    actual = {"state_vtable": mark.get("state_vtable"), "posted": posted,
              **{f: player(mark).get(f) for f in ("lives", "lives_lost")},
              **{f: mark.get(f) for f in ("pixels_sha256", "palette_sha256")}}
    wanted = {"state_vtable": expected["state_vtable"], "posted": expected["posted"],
              **{f: player(expected).get(f) for f in ("lives", "lives_lost")},
              **{f: expected["presentation"][f] for f in ("pixels_sha256", "palette_sha256")}}
    # Physical startup matters even while its images are no longer visible:
    # the timing countdown controls random-consuming actor state changes.
    # These are read-only observations, never inputs to the original replay.
    if "random_snapshot" in expected:
        actual["random_snapshot"] = mark.get("random_snapshot")
        wanted["random_snapshot"] = expected["random_snapshot"]
    differences = {field: {"actual": actual[field], "original": value}
                   for field, value in wanted.items() if actual[field] != value}
    return {"mark": name, "status": "fail" if differences else "pass", "differences": differences}



def claw_pids():
    found = subprocess.run(["pgrep", "-x", "Claw"], capture_output=True, text=True).stdout.split()
    return {int(p) for p in found}


SESSION = [None]


def sleep(seconds):
    SESSION[0].sleep(seconds)


def wait(predicate, seconds):
    if SESSION[0] is not None:
        return SESSION[0].wait(predicate, seconds)
    end = time.monotonic() + seconds
    while time.monotonic() < end:
        if predicate():
            return True
        time.sleep(0.05)
    return False


class Instance:
    def __init__(self, app, out, fast):
        self.app, self.out, self.pid, self.marks, self.order = app, out, None, {}, []
        self.session = SESSION[0] = Session(out, fast=fast, helper=HELPER)

    def read(self, name):
        try:
            return json.loads((self.out / name).read_text())
        except (OSError, ValueError):
            return {}

    def start(self):
        subprocess.run(["rm", "-rf", str(self.out)], check=True)
        self.out.mkdir(parents=True)
        (self.out / "menu-keys.json").write_text(json.dumps(MENU_KEYS))
        # Keep the original fixture's stationary cursor while real keys go to this PID.
        self.pid = self.session.launch(self.app, {"CLAW_REAL_SPEED_KEYS": self.out / "menu-keys.json"},
                                       [*(["--stationary-cursor"] if self.session.fast else []),
                                        "--responsiveness-check", "--save-dir", str(self.out / "saves"), "--menu-live-check", str(self.out),
                                        "-ClawCheckDirectory", str(self.out)])

    def level_running(self, seconds=90):
        return wait(lambda: self.read("live.json").get("state_vtable") == LEVEL
                    and (self.read("live.json").get("weapons") or {}).get("weapon") is not None
                    and self.read("live.json").get("game_ms", 0) > 1500, seconds)

    def key(self, name):
        for direction in ("down", "up"):
            self.session.post("press", MAC[name], direction)
            sleep(0.12)
        sleep(0.5)
        state = self.read("live-state.json")
        if state.get("status") != "running":
            raise RuntimeError(f"app {state.get('status')} {state.get('error')}")

    def mark(self, name):
        if self.session.mark(name) is None:
            raise RuntimeError(f"{name}: no presented frame record")
        if not self.session.fast:
            time.sleep(0.05)
        self.marks[name] = json.loads((self.out / f"{name}.json").read_text())
        self.order.append(name)
        return self.marks[name]

    def stop(self):
        self.session.close()


def player(mark):
    return mark.get("player") or {}


def posted_since(before, after):
    old, new = before.get("posted_commands") or [], after.get("posted_commands") or []
    return new[len(old):] if new[:len(old)] == old else new


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default=os.environ.get("CLAW_CONFIG", "Release"))
    parser.add_argument("--real-time", action="store_true", help="the display timer and wall-clock waits (pacing check)")
    parser.add_argument("--original-trace", type=Path, default=WORK / "original.json")
    args = parser.parse_args()
    fast = not real_time_requested(args.real_time)
    derived = Path(os.environ.get("CLAW_DERIVED_DATA", str(ROOT / "work" / "MacCatalyst")))
    app = derived / "Build" / "Products" / f"{args.config}-maccatalyst" / "Claw.app"
    result = {"check": "pause-gameover", "status": "fail", "config": args.config, "fast": fast, "errors": [], "steps": []}
    errors, steps = result["errors"], result["steps"]
    WORK.mkdir(parents=True, exist_ok=True)
    try:
        reference = original_reference(args.original_trace)
    except (OSError, ValueError, KeyError, TypeError) as error:
        errors.append(f"original trace: {error}")
        (WORK / "result.json").write_text(json.dumps(result, indent=1))
        print(json.dumps(result))
        return 1
    result["original_trace"] = str(args.original_trace)
    result["original_trace_sha256"] = hashlib.sha256(args.original_trace.read_bytes()).hexdigest()
    result["original_comparisons"] = []
    build_helper(HELPER)
    run = Instance(app, WORK / "check", fast)
    previous = {}

    def step(name, keys, state, lives=None, posted=(), settle=0.3, check=None):
        nonlocal previous
        for k in keys:
            run.key(k)
        sleep(settle)
        mark = run.mark(name)
        if mark.get("cursor_position") != [320, 240]:
            errors.append(f"{name}: physical cursor differs from the original stationary input: {mark.get('cursor_position')}")
        got = posted_since(previous, mark) if previous else mark.get("posted_commands") or []
        p = player(mark)
        comparison = compare_original(name, mark, got, reference[name])
        result["original_comparisons"].append(comparison)
        for field, difference in comparison["differences"].items():
            errors.append(f"{name}: original {field} mismatch: {difference}")
        steps.append({"mark": name, "state": mark.get("state_vtable"), "lives": p.get("lives"),
                      "lives_lost": p.get("lives_lost"), "health": p.get("health"), "game_ms": p.get("game_ms"),
                      "posted": got, "pixels": (mark.get("pixels_sha256") or "")[:16]})
        if mark.get("state_vtable") != state:
            errors.append(f"{name}: state {mark.get('state_vtable')}, expected {state}")
        if lives is not None and p.get("lives") != lives:
            errors.append(f"{name}: lives {p.get('lives')}, expected {lives}")
        for command in posted:
            if command not in got:
                errors.append(f"{name}: {command} not posted ({got})")
        if not posted and state == PAUSE and got and name != "pause-held":
            errors.append(f"{name}: unexpected posted commands {got}")
        if check:
            check(name, mark, errors)
        previous = mark
        return mark

    def no_held(name, mark, errs):
        live = run.read("live.json")
        held = (live.get("weapons") or {}).get("held_keys")
        if held:
            errs.append(f"{name}: held keys after resume {held}")

    try:
        run.start()
        if not run.level_running():
            raise RuntimeError("Level 1 did not start")
        sleep(1.0)
        start = step("play", [], LEVEL)
        lives = player(start).get("lives")
        result["starting_lives"] = lives
        if not isinstance(lives, int) or lives < 1:
            raise RuntimeError(f"no lives counter: {player(start)}")
        # Pause: the menu state is up and the game clock and frame stay still while it waits.
        pause = step("pause", ["esc"], PAUSE, lives, posted=["0x8080"])
        sleep(1.5)
        step("pause-held", [], PAUSE, lives)
        resume = step("resume", ["ret"], LEVEL, lives, posted=["0x8036"], check=no_held)
        # Check the clock at the actual state transitions after the log is flushed
        # below. These marks occur after key/settle waits: the menu advances its
        # own clock, so subtracting their timestamps tests checker scheduling.
        sleep(1.0)
        # End Life, No: back to the main page, then Escape resumes with the same lives.
        step("endlife-page", END_LIFE, PAUSE, lives, posted=["0x8080"])
        step("endlife-no", ["down", "ret"], PAUSE, lives)
        step("endlife-no-resume", ["esc"], LEVEL, lives, posted=["0x8036"], check=no_held)
        sleep(1.0)
        # End Game, No.
        step("endgame-page", END_GAME, PAUSE, lives, posted=["0x8080"])
        step("endgame-no", ["down", "ret"], PAUSE, lives)
        step("endgame-no-resume", ["esc"], LEVEL, lives, posted=["0x8036"], check=no_held)
        sleep(1.0)
        # End Life, Yes, until the last life: each loses one life and respawns; the last one goes to the menu.
        remaining = lives
        index = 0
        while remaining > 0 and index < 12:
            index += 1
            run.key("esc")
            run.key("down")
            run.key("ret")
            run.key("ret")
            remaining -= 1
            if remaining > 0:
                ok = wait(lambda: run.read("live.json").get("state_vtable") == LEVEL
                          and run.read("live.json").get("lives") == remaining
                          and run.read("live.json").get("health") == 100, 20)
                sleep(1.5)
                m = step(f"endlife-yes-{index}", [], LEVEL, remaining, posted=["0x8036", "0x8063", "0x803a"],
                         check=no_held)
                if not ok:
                    errors.append(f"endlife-yes-{index}: no respawn with {remaining} lives")
                if player(m).get("lives_lost") != player(start).get("lives_lost", 0) + index:
                    errors.append(f"endlife-yes-{index}: lives lost {player(m).get('lives_lost')}")
            else:
                ok = wait(lambda: run.read("live.json").get("state_vtable") == MENU, 20)
                sleep(2.0)
                step("gameover-menu", [], MENU, posted=["0x8036", "0x8063", "0x8006"])
                if not ok:
                    errors.append("gameover-menu: no menu after the last life")
                if any(s.get("state") == "0x50bfec" for s in steps):
                    errors.append("game over state 12 entered in the retail build")
        # New Game from the menu that the game over left selected, then End Game Yes back to the menu.
        # The menu takes keys only once its entrance has settled (the start-up route also waits 3 s), so
        # Return is pressed again every 3 s until the level starts loading.
        presses = 0
        while presses < 4 and run.read("live.json").get("state_vtable") == MENU:
            run.key("ret")
            presses += 1
            wait(lambda: run.read("live.json").get("state_vtable") != MENU, 3)
        result["new_game_presses"] = presses
        if not run.level_running(60):
            raise RuntimeError("New Game after game over did not reach Level 1")
        sleep(1.0)
        again = step("newgame", [], LEVEL, lives)
        if player(again).get("lives_lost") != player(start).get("lives_lost"):
            errors.append(f"newgame: lives lost {player(again).get('lives_lost')}")
        step("endgame-page-2", END_GAME, PAUSE, lives, posted=["0x8080"])
        run.key("ret")
        ok = wait(lambda: run.read("live.json").get("state_vtable") == MENU, 20)
        sleep(2.0)
        step("endgame-yes", [], MENU, posted=["0x8036", "0x8023"])
        if not ok:
            errors.append("endgame-yes: no menu")
        heartbeats = run.read("live.json").get("responsiveness", [])
        errors.extend(check_heartbeats(heartbeats, required=("0x4ec9c0",)))
        # Startup, game over, and End Game each return through a blocking
        # screen transition; never accept a probe that observed only startup.
        transitions = [r for r in heartbeats if r.get("scope") == "0x4ec9c0"]
        if len(transitions) < 3:
            errors.append(f"only {len(transitions)} screen transitions observed (requires >=3)")
        result["heartbeat_scopes"] = len(heartbeats)
        result["heartbeat_max_gap_ms"] = max((r["max_gap_ms"] for r in heartbeats), default=None)
        final = run.read("live-state.json")
        if final.get("status") != "running":
            errors.append(f"final: app {final.get('status')} {final.get('error')}")
    except Exception as error:  # noqa: BLE001 - reported as the check's failure
        errors.append(str(error))
    finally:
        try:
            if run.pid:
                sleep(1.0)
        except RuntimeError as error:
            errors.append(str(error))
        finally:
            run.stop()
    # Window events the system dropped and the driver posted again (bounded, scripts/real_input.py): reported,
    # not failed; every step's state, lives and posted commands are still compared.
    result["retries"] = run.session.retries
    boundary = []
    previous_state = None
    for frame in run.read("real-speed.json").get("frames", []):
        state = frame.get("state_vtable")
        if state is None:
            continue
        if state != previous_state:
            if not boundary and previous_state == LEVEL[2:] and state == PAUSE[2:]:
                boundary.append(frame)
            elif boundary and previous_state == PAUSE[2:] and state == LEVEL[2:]:
                boundary.append(frame)
                break
        previous_state = state
    clocks = [player(frame).get("game_ms") for frame in boundary]
    if len(clocks) != 2 or any(not isinstance(value, int) for value in clocks):
        errors.append("pause/resume: missing game clock at the state transition")
    else:
        paused_ms = clocks[1] - clocks[0]
        result["game_ms_across_pause"] = paused_ms
        result["pause_clock_boundaries"] = [
            {"frame": frame["frame"], "state": frame["state_vtable"], "game_ms": player(frame)["game_ms"]}
            for frame in boundary]
        if not 0 <= paused_ms < 200:
            errors.append(f"resume: game clock moved {paused_ms} ms across the pause")
    # Evidence compared between the fast and real-time runs (scripts/compare-real-input.py): no clock or pixels.
    (WORK / "check" / "evidence.json").write_text(json.dumps({"steps": [{k: v for k, v in st.items()
        if k not in ("game_ms", "pixels")} for st in steps], "starting_lives": result.get("starting_lives")},
        indent=1, sort_keys=True))  # new_game_presses: Returns every 3 s until the menu takes one, a timing count
    if run.order != list(MARKS):
        errors.append(f"original comparison: incomplete mark sequence {run.order}")
    if not errors:
        result["status"] = "pass"
    (WORK / "result.json").write_text(json.dumps(result, indent=1))
    print(json.dumps(result))
    return 0 if result["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())

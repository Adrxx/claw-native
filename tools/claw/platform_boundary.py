"""What the game code calls in the platform layer: imports, C runtime and MFC. One JSON line.

    python -m tools.claw.platform_boundary

The platform layer is replaced by native code, not recovered. This lists exactly what that native layer must
provide, grouped by library, with how many game functions depend on each entry. Writes docs/PLATFORM-BOUNDARY.md.
"""
import json
import sys

from . import index, progress_page
from .paths import DOCS


def main(argv):
    functions = index.functions()
    symbols = index.symbols()
    imports = {a: s["name"] for a, s in symbols.items() if s["kind"] == "import"}
    game = [a for a in functions if progress_page.in_game(a)]
    targets = {}
    for caller in game:
        for target, sites in index.call_targets(caller).items():
            if target in imports:
                kind, name = "import", imports[target]
            elif target in functions and not progress_page.in_game(target):
                kind = "mfc" if target >= 0x4F0000 else "c-runtime"
                name = index.name(target) or functions[target].get("name", "")
            else:
                continue
            entry = targets.setdefault(target, {"address": f"{target:#x}", "kind": kind, "name": name, "callers": set(), "sites": 0})
            entry["callers"].add(caller)
            entry["sites"] += sites
    rows = sorted(targets.values(), key=lambda e: (e["kind"], -len(e["callers"])))
    by_kind = {}
    for row in rows:
        by_kind.setdefault(row["kind"], []).append(row)
    lines = ["# Platform boundary", "", "Generated by `make platform-boundary`. What game code calls directly in the platform layer.",
             "Everything listed here is provided by native code. None of it is recovered instruction by instruction.", ""]
    titles = {"import": "Windows and DirectX imports", "c-runtime": "C runtime functions (approximate range)",
              "mfc": "MFC functions (approximate range)"}
    for kind in ("import", "mfc", "c-runtime"):
        entries = by_kind.get(kind, [])
        lines += [f"## {titles[kind]}: {len(entries)}", "", "| Address | Name | Game functions calling it | Call sites |",
                  "| --- | --- | ---: | ---: |"]
        lines += [f"| {e['address']} | {e['name']} | {len(e['callers'])} | {e['sites']} |" for e in entries]
        lines.append("")
    (DOCS / "PLATFORM-BOUNDARY.md").write_text("\n".join(lines))
    print(json.dumps({"command": "platform-boundary", "game_functions": len(game),
                      "entries": {k: len(v) for k, v in by_kind.items()}, "output": "docs/PLATFORM-BOUNDARY.md",
                      "status": "pass"}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

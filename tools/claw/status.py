"""Regenerates docs/STATUS.md from the family manifests. One JSON line.

The document is a table of where every family stands on two independent scales: how strong its evidence is, and how
far it is integrated into the app. Nothing in it is typed by hand.
"""
import datetime
import json
import sys

from . import index, manifest
from .paths import DOCS

EVIDENCE = ["none", "provisional", "legacy-frozen", "admitted"]
INTEGRATION = ["source-only", "compiled", "elected", "live"]
EVIDENCE_TEXT = {
    "none": "No comparison against the original exists.",
    "provisional": "A comparison exists; nobody independent has checked it.",
    "legacy-frozen": "Codex's coordinator re-ran the worker's own comparison.",
    "admitted": "Passed the admission gate (docs/ADMISSION.md).",
}
INTEGRATION_TEXT = {
    "source-only": "Not compiled into the app.",
    "compiled": "Compiled into the app; host election is not recorded.",
    "elected": "Wired from a Swift host; recorded original-call-graph app trace pending.",
    "live": "Reached through the original call graph in a recorded app trace.",
}


def _percent(part, whole):
    return f"{100 * part / whole:.0f}%" if whole else "n/a"


def render():
    manifests = manifest.load_all()
    game = {n: m for n, m in manifests.items() if not n.startswith(("example_", "selftest"))}
    lines = ["# Status", "", f"Generated by `make status` on {datetime.date.today().isoformat()} from the "
             f"{len(game)} manifests in `Tests/families/`. Do not edit by hand.", "",
             "The complete single-player game is playable on iPad and Mac (all 14 levels, custom and CrazyHook levels). The tables below track how much of the original code is recovered and verified.", "",
             "## Families by evidence and integration", "",
             "| Evidence \\ Integration | " + " | ".join(INTEGRATION) + " | Total |",
             ("| --- | " + "--- | " * (len(INTEGRATION) + 1)).rstrip()]
    for level in EVIDENCE:
        row = [sum(1 for m in game.values() if m["evidence"]["level"] == level and m["integration"]["level"] == i)
               for i in INTEGRATION]
        lines.append(f"| {level} | " + " | ".join(str(n) for n in row) + f" | {sum(row)} |")
    totals = [sum(1 for m in game.values() if m["integration"]["level"] == i) for i in INTEGRATION]
    lines.append("| Total | " + " | ".join(str(n) for n in totals) + f" | {sum(totals)} |")
    lines += ["", "Evidence levels:", ""] + [f"- **{k}**: {v}" for k, v in EVIDENCE_TEXT.items()]
    lines += ["", "Integration levels:", ""] + [f"- **{k}**: {v}" for k, v in INTEGRATION_TEXT.items()]

    baseline = [m["evidence"].get("baseline") for m in game.values() if m["evidence"].get("baseline")]
    if baseline:
        passing = sum(1 for b in baseline if b["status"] == "pass")
        lines += ["", "## Latest plain re-run of the legacy comparisons", "",
                  f"{passing} of {len(baseline)} families pass when their comparison scripts are simply run again "
                  f"({baseline[0]['date']}).", ""]
        failing = sorted(n for n, m in game.items() if (m["evidence"].get("baseline") or {}).get("status") == "fail")
        if failing:
            lines += ["Failing: " + ", ".join(f"`{n}`" for n in failing) + "."]

    gates = {n: m["evidence"]["gate"] for n, m in game.items() if (m["evidence"].get("gate") or {}).get("kind") == "legacy-measurement"}
    if gates:
        salted = sum(1 for g in gates.values() if g["salted"] == "pass")
        called = sum(1 for g in gates.values() if g["owned"] and g["directly_called"] == g["owned"])
        full = sum(1 for g in gates.values() if g["bytes_owned"] and g["bytes_executed"] == g["bytes_owned"])
        owned_bytes = sum(g["bytes_owned"] for g in gates.values())
        run_bytes = sum(g["bytes_executed"] for g in gates.values())
        lines += ["", "## Measurement of the legacy families", "",
                  "Each family's comparison was run in a private copy of the tree, once as written and once with "
                  "every random seed changed, while recording which original instructions ran (`make regate`).", "",
                  "| Measure | Families |", "| --- | --- |", f"| Measured | {len(gates)} |",
                  f"| Pass with seeds the author never saw | {salted} |",
                  f"| Every owned function is called directly by a test | {called} |",
                  f"| Every byte of every owned function was executed | {full} |", "",
                  f"Across all measured families the tests executed {_percent(run_bytes, owned_bytes)} of the bytes "
                  f"of the functions they own ({run_bytes:,} of {owned_bytes:,})."]

    try:
        functions = index.functions()
        owned = set()
        for m in game.values():
            if m["evidence"]["level"] != "none":
                owned |= {int(o["address"], 16) for o in m["owned"]}
        real = {a: f for a, f in functions.items() if f["size"] >= 16}
        owned_bytes = sum(f["size"] for a, f in functions.items() if a in owned)
        game_bytes = sum(f["size"] for a, f in real.items() if a < 0x4A0000)
        lines += ["", "## Share of the original recovered", "",
                  f"The manifests list {len(owned & set(functions))} original functions as owned by modules with comparison evidence, "
                  f"{owned_bytes:,} bytes. The function index holds {len(real):,} functions of 16 bytes or more; those "
                  f"below the C runtime and library code (address under 0x4a0000) total {game_bytes:,} bytes. "
                  f"That puts the recovered share of game code near {_percent(owned_bytes, game_bytes)}. Ownership "
                  f"lists for legacy families are incomplete, so treat this as a lower bound on comparison-backed "
                  f"declared ownership. Families with evidence `none`, including unimplemented canonical drafts, "
                  f"are excluded. This includes provisional and legacy evidence; it is not an admitted-code or "
                  f"playability percentage. Baselines and legacy measurements above retain their separate meaning."]
    except FileNotFoundError:
        pass

    lines += ["", "## Every family", "", "| Family | What it is | Evidence | Integration | Plain re-run | Unseen seeds | Owned bytes executed |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for name in sorted(game):
        m = game[name]
        base = (m["evidence"].get("baseline") or {}).get("status", "")
        gate = m["evidence"].get("gate") or {}
        coverage = f"{100 * gate['coverage']:.0f}%" if gate.get("coverage") is not None else ""
        lines.append(f"| `{name}` | {m['title'][:70]} | {m['evidence']['level']} | {m['integration']['level']} | {base} | "
                     f"{gate.get('salted', '')} | {coverage} |")
    return "\n".join(lines) + "\n", len(game)


def main(argv):
    text, count = render()
    (DOCS / "STATUS.md").write_text(text)
    print(json.dumps({"command": "status", "families": count, "output": "docs/STATUS.md", "status": "pass"}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
